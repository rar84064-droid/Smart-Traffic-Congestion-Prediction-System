"""# step 1.1 - Load and Explore Dataset"""

df = pd.read_csv("Metro_Interstate_Traffic_Volume.csv")

""" **Shape & *first* 5 rows & Missing Values &  Class Distribution**"""

print(f"Shape: {df.shape}")
